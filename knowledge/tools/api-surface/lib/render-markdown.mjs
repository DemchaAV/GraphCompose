/**
 * tools/api-surface/lib/render-markdown.mjs — the allow-list as prose.
 *
 * `api-surface.json` is the contract; this is the copy a person reads and an
 * agent greps when it has no better tool to hand. It is generated from the
 * JSON and never edited, so the two cannot disagree — which is the whole reason
 * the JSON was introduced rather than a second parser.
 *
 * Deliberately no timestamp in the output. A regenerated-today field makes
 * every run differ from the last, which would turn the `--check` gate into
 * noise; what validates this file is the version it was read from, and that is
 * in the frontmatter.
 */

const HEADER_NOTE =
  "Generated from the pinned artifact's class files. Authoritative closed set: a symbol " +
  "absent here does not exist for this version. Regenerate, do not hand-edit.";

/**
 * Stability rides in the rendered line, not only in the JSON.
 *
 * The Markdown is what an agent greps when it has no query tool to hand, so a
 * `@Beta` member that renders identically to a stable one tells it the opposite
 * of the truth. `DocumentSession.toPptxBytes()` and the `SvgPath` overload of
 * `ShapeContainerBuilder.path` are beta on otherwise stable types; without this
 * marker both read as settled API.
 */
const mark = (stability) => (stability && stability !== "stable" ? `   [${stability}]` : "");

function renderMember(member) {
  if (member.kind === "constant") return null;

  const params = member.params
    .map((p) => (p.name ? `${p.type} ${p.name}` : p.type))
    .join(", ");

  if (member.kind === "constructor") return `new ${member.name}(${params})${mark(member.stability)}`;

  const prefix = member.typeParameters ? `${member.typeParameters} ` : "";
  const returns = member.returns ? `${member.returns} ` : "";
  return `${prefix}${returns}${member.name}(${params})${mark(member.stability)}`;
}

export function renderMarkdown(surface) {
  const out = [];

  out.push(
    "---",
    "skillId: graphcompose-api-surface",
    `targetLibrary: ${surface.targetLibrary}`,
    `targetVersion: ${surface.targetVersion}`,
    `verifiedAgainst: ${surface.verifiedAgainst}`,
    "status: active",
    `generator: ${surface.generator}`,
    `generatedFrom: "${surface.generatedFrom.join(", ")}"`,
    `note: "${HEADER_NOTE}"`,
    "---",
    "",
    `# GraphCompose — Public API Surface (${surface.surface})`,
    "",
    `> **Generated from \`${surface.generator}\` — do not hand-edit.**`,
    `> This is the COMPLETE list of public methods and constants on the \`${surface.surface}\` surface,`,
    "> read from the pinned artifact's class files — so members generated by Lombok",
    "> (`builder()`, `toBuilder()`, getters, nested `…Builder` types) are present, which",
    "> they cannot be when the source text is parsed instead.",
    "> **If a member is not listed here, it does not exist — do not invent one.**",
    "> Types marked `[beta]` carry `@Beta`: usable, but the contract can still change.",
    "> `@Internal` types and members are excluded on purpose; `excluded.json` records each one.",
    ">",
    "> This is one surface of several. The others are listed beside it in",
    "> `knowledge/api/`; a task should load the one it needs, not all of them.",
    ">",
    "> Ask it a question instead of reading it:",
    "> `node knowledge/tools/api-query/api-query.mjs --search <term>`.",
    "",
    `**GraphCompose version:** ${surface.verifiedAgainst}`,
    "",
    `Types: ${surface.counts.types} · methods: ${surface.counts.methods} · ` +
      `constants: ${surface.counts.constants} · compiler-generated members: ${surface.counts.generated}`,
    "",
  );

  for (const pkg of surface.packages) {
    out.push("", `## ${pkg.name}`, "");
    for (const type of pkg.types) {
      out.push(`### ${type.name} (${type.kind})${mark(type.stability)}`);
      for (const member of type.members) {
        const rendered = renderMember(member);
        if (rendered) out.push(`- \`${rendered}\``);
      }
      const constants = type.members.filter((m) => m.kind === "constant").map((m) => `\`${m.name}\``);
      if (constants.length) out.push(`- constants: ${constants.join(", ")}`);
      out.push("");
    }
  }

  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
